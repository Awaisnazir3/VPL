const { spawn } = require('child_process');
require('dotenv').config();

const ASTERISK_HOST = process.env.ASTERISK_HOST || '192.168.88.47';
const ASTERISK_SSH_USER = process.env.ASTERISK_SSH_USER || 'root';

/**
 * Execute a bash script on the Asterisk server via SSH stdin (safe from any quoting issues)
 */
function runSsh(script) {
  return new Promise((resolve, reject) => {
    const child = spawn('ssh', [
      '-o', 'BatchMode=yes',
      '-o', 'StrictHostKeyChecking=no',
      '-o', 'ConnectTimeout=8',
      `${ASTERISK_SSH_USER}@${ASTERISK_HOST}`,
      'bash -s'
    ]);

    let stdout = '';
    let stderr = '';

    child.stdout.on('data', data => { stdout += data; });
    child.stderr.on('data', data => { stderr += data; });

    child.on('close', code => {
      if (code !== 0) {
        return reject(new Error(stderr.trim() || `SSH exited with code ${code}`));
      }
      resolve(stdout.trim());
    });

    child.on('error', err => reject(err));

    child.stdin.write(script);
    child.stdin.end();
  });
}

/**
 * Provision or update a WebRTC PJSIP Extension on Asterisk 192.168.88.47
 */
async function provisionExtension(extension, secret) {
  const ext = String(extension).trim();
  const pass = String(secret).trim();

  console.log(`[Asterisk Provisioner] Provisioning extension ${ext} on ${ASTERISK_HOST}...`);

  const stanza = `
; Provisioned User for Order ID ${ext}
[${ext}](webrtc-profile)
auth=auth-${ext}
aors=${ext}

[auth-${ext}]
type=auth
auth_type=userpass
username=${ext}
password=${pass}

[${ext}]
type=aor
max_contacts=5
remove_existing=yes
default_expiration=60
minimum_expiration=30
maximum_expiration=120
`;

  // Safely clean existing stanzas for this extension from pjsip.conf and pjsip_vpl.conf, then append
  const remoteScript = `
touch /etc/asterisk/pjsip.conf
sed -i '/; Provisioned User for Order ID ${ext}/,/maximum_expiration=120/d' /etc/asterisk/pjsip.conf
sed -i '/; --- Extension ${ext} ---/,/remove_existing=yes/d' /etc/asterisk/pjsip.conf
sed -i '/; --- Extension ${ext} ---/,/remove_existing=yes/d' /etc/asterisk/pjsip_vpl.conf 2>/dev/null || true

cat << 'EOF' >> /etc/asterisk/pjsip.conf
${stanza.trim()}
EOF

asterisk -rx "pjsip reload"
`;

  const output = await runSsh(remoteScript);
  console.log(`[Asterisk Provisioner] Extension ${ext} provisioned successfully:`, output);
  return { success: true, extension: ext, output };
}

/**
 * Sync all DID forwarding rules to Asterisk dialplan /etc/asterisk/extensions_vpl.conf
 */
async function syncDidRoutes(routes) {
  console.log(`[Asterisk Provisioner] Syncing ${routes.length} DID routes on ${ASTERISK_HOST}...`);

  let dialplanBody = `
; ============================================
; VPL Customer Portal Dynamic Dialplan
; Auto-generated by VPL Portal Backend
; ============================================

[vpl-internal]
; Allow dialing any 4-digit extension (1001, 2001, 2002, etc.)
exten => _[1-9]XXX,1,NoOp(=== Internal Call from \${CALLERID(num)} to \${EXTEN} ===)
 same => n,Dial(PJSIP/\${EXTEN},30,tT)
 same => n,NoOp(Internal dial status: \${DIALSTATUS})
 same => n,Hangup()

; Allow dialing *43 for echo test
exten => *43,1,NoOp(=== WebRTC Echo Test ===)
 same => n,Answer()
 same => n,Playback(demo-echotest)
 same => n,Echo()
 same => n,Playback(demo-echodone)
 same => n,Hangup()

[vpl-dids]
`;

  for (const r of routes) {
    const rawDid = String(r.did_number || '').trim();
    const cleanDid = rawDid.replace(/[^0-9+]/g, '');
    const numOnly = cleanDid.replace(/^\+/, '');
    const forwardType = r.forward_type;
    const dest = String(r.forward_destination || '').trim();
    const vmEnabled = (r.voicemail_enabled === 1 || r.voicemail_enabled === true || r.voicemail_enabled === '1');
    const vmTimeout = (r.voicemail_timeout !== undefined && r.voicemail_timeout !== null) ? parseInt(r.voicemail_timeout, 10) : 20;

    if (!cleanDid || !dest) continue;

    const didVariants = [cleanDid];
    if (cleanDid !== numOnly) didVariants.push(numOnly);

    // Determine dial target string
    let dialTarget = '';
    if (forwardType === 'PSTN') {
      dialTarget = `PJSIP/${dest}@\${OUTBOUND_TRUNK}`;
    } else {
      if (/^[0-9]{4,6}$/.test(dest)) {
        dialTarget = `PJSIP/${dest}`;
      } else {
        const sipUri = dest.startsWith('sip:') ? dest : `sip:${dest}`;
        dialTarget = `PJSIP/anonymous/${sipUri}`;
      }
    }

    for (const did of didVariants) {
      dialplanBody += `
exten => ${did},1,NoOp(=== Inbound DID Call: ${did} -> ${forwardType} -> ${dest} (Voicemail: ${vmEnabled ? 'ON ' + vmTimeout + 's' : 'OFF'}) ===)
 same => n,Set(CALLERID(all)=\${CALLERID(all)})
`;
      if (vmEnabled && vmTimeout === 0) {
        // Immediate Voicemail / DND
        dialplanBody += ` same => n,NoOp(=== Immediate Voicemail for ${did} ===)\n`;
        dialplanBody += ` same => n,Answer()\n`;
        dialplanBody += ` same => n,Wait(1)\n`;
        dialplanBody += ` same => n,Playback(vm-intro)\n`;
        dialplanBody += ` same => n,Set(VM_FILE=/tmp/vm-${did}-\${EPOCH})\n`;
        dialplanBody += ` same => n,Record(\${VM_FILE}.wav,3,120,k)\n`;
        dialplanBody += ` same => n,Playback(auth-thankyou)\n`;
        dialplanBody += ` same => n,System(curl -s -F "file=@\${VM_FILE}.wav" -F "caller_id=\${CALLERID(num)}" -F "did_number=${did}" -F "duration=\${RECORDED_DURATION}" http://192.168.88.119/api/voicemails/upload)\n`;
        dialplanBody += ` same => n,System(rm -f \${VM_FILE}.wav)\n`;
        dialplanBody += ` same => n,Hangup()\n`;
      } else if (vmEnabled && vmTimeout > 0) {
        // Ring for timeout, then fallback to Voicemail on no-answer
        dialplanBody += ` same => n,Dial(${dialTarget},${vmTimeout},tT)\n`;
        dialplanBody += ` same => n,GotoIf($["\${DIALSTATUS}" = "ANSWER"]?done)\n`;
        dialplanBody += ` same => n,NoOp(=== DID ${did} Unanswered (\${DIALSTATUS}) -> Forwarding to Voicemail ===)\n`;
        dialplanBody += ` same => n,Answer()\n`;
        dialplanBody += ` same => n,Wait(1)\n`;
        dialplanBody += ` same => n,Playback(vm-intro)\n`;
        dialplanBody += ` same => n,Set(VM_FILE=/tmp/vm-${did}-\${EPOCH})\n`;
        dialplanBody += ` same => n,Record(\${VM_FILE}.wav,3,120,k)\n`;
        dialplanBody += ` same => n,Playback(auth-thankyou)\n`;
        dialplanBody += ` same => n,System(curl -s -F "file=@\${VM_FILE}.wav" -F "caller_id=\${CALLERID(num)}" -F "did_number=${did}" -F "duration=\${RECORDED_DURATION}" http://192.168.88.119/api/voicemails/upload)\n`;
        dialplanBody += ` same => n,System(rm -f \${VM_FILE}.wav)\n`;
        dialplanBody += ` same => n(done),Hangup()\n`;
      } else {
        // Voicemail disabled: normal ring 60s
        dialplanBody += ` same => n,Dial(${dialTarget},60,tT)\n`;
        dialplanBody += ` same => n,Hangup()\n`;
      }
    }
  }

  const remoteScript = `
cat << 'EOF_EXT' > /etc/asterisk/extensions_vpl.conf
${dialplanBody.trim()}
EOF_EXT
asterisk -rx 'dialplan reload'
`;

  const output = await runSsh(remoteScript);
  console.log(`[Asterisk Provisioner] Dialplan reloaded successfully:`, output);
  return { success: true, count: routes.length };
}

/**
 * Unprovision / delete an extension from Asterisk 192.168.88.47
 */
async function unprovisionExtension(extension) {
  const ext = String(extension).trim();
  console.log(`[Asterisk Provisioner] Removing extension ${ext} from ${ASTERISK_HOST}...`);

  const remoteScript = `
sed -i '/; Provisioned User for Order ID ${ext}/,/maximum_expiration=120/d' /etc/asterisk/pjsip.conf
sed -i '/; --- Extension ${ext} ---/,/remove_existing=yes/d' /etc/asterisk/pjsip.conf
sed -i '/; --- Extension ${ext} ---/,/remove_existing=yes/d' /etc/asterisk/pjsip_vpl.conf 2>/dev/null || true
asterisk -rx "pjsip reload"
`;

  const output = await runSsh(remoteScript);
  console.log(`[Asterisk Provisioner] Extension ${ext} removed successfully:`, output);
  return { success: true, extension: ext, output };
}

/**
 * Test Asterisk host reachability and PJSIP status
 */
async function testAsterisk() {
  try {
    const uptime = await runSsh("asterisk -rx 'core show uptime' || asterisk -rx 'core show version'");
    return { online: true, host: ASTERISK_HOST, message: uptime };
  } catch (err) {
    return { online: false, host: ASTERISK_HOST, error: err.message };
  }
}

